// ============================================================================
// PAGE
// ============================================================================

export default function DoctorSlotsPage() {
  const [loading, setLoading] = useState(false);

  const uploadSlots = async () => {
    setLoading(true);

    try {
      for (const doctor of doctorSlots) {
        const { doctorId, doctorName, ...weeklySlots } = doctor;

        // Use the existing slots collection.
        // The doctor ID becomes the document ID.
        const slotRef = doc(slotsCollection, doctorId);

        await setDoc(slotRef, {
          doctorId,
          doctorName,

          // Monday-Saturday slots
          ...weeklySlots,

          // All appointments are 30 minutes
          slotDuration: 30,

          updatedAt: new Date(),
        });
      }

      alert("Slots for all 5 doctors saved successfully!");
    } catch (error) {
      console.error("Error saving doctor slots:", error);
      alert("Failed to save doctor slots.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <main style={{ padding: "40px" }}>
      <h1>Doctor Slots</h1>

      <p>
        Configure Monday to Saturday appointment slots for all 5 doctors.
      </p>

      <button
        onClick={uploadSlots}
        disabled={loading}
        style={{
          padding: "12px 24px",
          marginTop: "20px",
          cursor: loading ? "not-allowed" : "pointer",
        }}
      >
        {loading ? "Saving Slots..." : "Save Doctor Slots"}
      </button>
    </main>
  );
}
